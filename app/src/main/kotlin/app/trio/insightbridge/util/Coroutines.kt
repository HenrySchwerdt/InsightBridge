package app.trio.insightbridge.util

import app.aaps.pump.insight.utils.PumpLog
import kotlin.coroutines.CoroutineContext
import kotlin.coroutines.EmptyCoroutineContext
import kotlinx.coroutines.CoroutineExceptionHandler
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.CoroutineStart
import kotlinx.coroutines.Job
import kotlinx.coroutines.launch

/** Handler that logs instead of crashing the process; every scope in the app carries it. */
val LoggingExceptionHandler = CoroutineExceptionHandler { _, t -> PumpLog.e("Unhandled coroutine failure", t) }

fun CoroutineScope.launchSafely(
    context: CoroutineContext = EmptyCoroutineContext,
    start: CoroutineStart = CoroutineStart.DEFAULT,
    block: suspend CoroutineScope.() -> Unit
): Job = launch(context + LoggingExceptionHandler, start, block)
